# Examples of basic data types in Python
age = 20                  # int
percentage = 87.5         # float
college = "ABC College"   # str
is_passed = True          # bool

print(age, "->", type(age))
print(percentage, "->", type(percentage))
print(college, "->", type(college))
print(is_passed, "->", type(is_passed))
