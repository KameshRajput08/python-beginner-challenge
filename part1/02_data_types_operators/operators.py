a = 10
b = 5

print("Comparison Operators:")
print("a == b:", a == b)
print("a != b:", a != b)
print("a > b:", a > b)
print("a < b:", a < b)
print("a >= 10:", a >= 10)
print("b <= 3:", b <= 3)

print("\nLogical Operators:")
has_id = True
age = 19

print("age >= 18 and has_id:", age >= 18 and has_id)
print("age < 18 or has_id:", age < 18 or has_id)
print("not has_id:", not has_id)
